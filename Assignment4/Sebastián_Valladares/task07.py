"""**TASK 7.3:**

Spanish: Enumera el nombre y el tipo de quienes conocen a Curry (solo en SPARQL). Utiliza el nombre y el tipo como variables en la consulta.

English: List the name and type of those who know Curry (in SPARQL only). Use name and type as variables in the query
"""

#TODO

query =  """
PREFIX ns:  <http://oeg.fi.upm.es/def/people#>

SELECT DISTINCT ?name ?type WHERE {
  ?person ?k ?curry .
  FILTER(CONTAINS(STR(?k), "knows"))

  OPTIONAL { ?curry ?pC ?cVal }
  FILTER(CONTAINS(STR(?curry), "Curry") || (BOUND(?cVal) && CONTAINS(STR(?cVal), "Curry")))

  ?person <http://www.w3.org/1999/02/22-rdf-syntax-ns#type> ?type .

  ?person ?pName ?name .
  FILTER(?pName IN (
    <http://www.w3.org/2001/vcard-rdf/3.0#Given>,
    <http://www.w3.org/2001/vcard-rdf/3.0#FN>,
    <http://xmlns.com/foaf/0.1/givenName>,
    <http://xmlns.com/foaf/0.1/name>,
    <http://www.w3.org/2000/01/rdf-schema#label>,
    ns:hasName
  ))
}
"""

# Visualize the results
for r in g.query(query):
  print(r.name, r.type)

